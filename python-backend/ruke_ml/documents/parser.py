"""Format-aware extraction that preserves relationships, not flattened text.

Stdlib OOXML reader: shared strings, sheet identity, cell types, FORMULA plus the cached
result, merged ranges, hyperlinks, slide notes, docx heading levels and table cells.
Supplementary-plane characters (astral emoji) decode correctly because the XML parser,
not String.fromCharCode-style code-unit math, resolves the entities.
"""
from __future__ import annotations

import re
import zipfile
from pathlib import Path
from typing import Iterable
from xml.etree import ElementTree as ET

from ..contracts import sha256_hex
from .structures import Block, DocCoverage, Document

_MAIN_NS = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
_W_NS = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
_A_NS = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
_P_NS = "{http://schemas.openxmlformats.org/presentationml/2006/main}"

# Placeholder shapes a notesSlide owns automatically: slide number, footer, header and
# date fields are generated by the template, never authored. Text inside them is not a
# speaker note, so joining every <a:t> in the part invents note content (a deck with no
# notes reported "1"/"2"/"3" as notes) and pollutes real notes with a trailing number.
_NOTES_PLACEHOLDER_TYPES = frozenset({"sldNum", "ftr", "hdr", "dt"})


class ExtractionRejected(Exception):
    pass


_CELL_REF = re.compile(r"\$?([A-Z]+)\$?([1-9][0-9]*)", re.ASCII)


def cell_xy(ref: str) -> tuple[int, int]:
    """(column, row) for an A1-style reference, 1-based, absolute markers ignored."""
    match = _CELL_REF.fullmatch(ref.strip().upper())
    if match is None:
        raise ExtractionRejected(f"Invalid cell reference: {ref!r}")

    col = 0
    for char in match.group(1):
        col = col * 26 + ord(char) - ord("A") + 1

    return col, int(match.group(2))


def range_bounds(ref: str) -> tuple[int, int, int, int]:
    """Normalised (x1, y1, x2, y2) for `A1:B2`, or for a lone `A1`."""
    first, separator, last = ref.partition(":")
    x1, y1 = cell_xy(first)
    x2, y2 = cell_xy(last if separator else first)

    return min(x1, x2), min(y1, y2), max(x1, x2), max(y1, y2)


def _merged_index(merged: list[tuple[str, tuple[int, int, int, int]]]) -> dict[int, list]:
    """Row-index the merged areas so cell lookups stay bounded on large sheets.

    A per-cell linear scan over every merge is quadratic on a big sheet; row spans are
    normally tiny, so each area is filed under each row it covers, and an implausibly
    tall merge is kept in the fallback list instead of being expanded.
    """
    by_row: dict[int, list] = {}
    overflow: list = []
    for area, (x1, y1, x2, y2) in merged:
        if y2 - y1 > 256:
            overflow.append((area, (x1, y1, x2, y2)))
            continue
        for y in range(y1, y2 + 1):
            by_row.setdefault(y, []).append((area, (x1, y1, x2, y2)))
    return {"by_row": by_row, "overflow": overflow}


def _merged_for(ref: str, index: dict) -> str | None:
    x, y = cell_xy(ref)
    for area, (x1, y1, x2, y2) in index["by_row"].get(y, ()):
        if x1 <= x <= x2:
            return area
    for area, (x1, y1, x2, y2) in index["overflow"]:
        if x1 <= x <= x2 and y1 <= y <= y2:
            return area
    return None


def load_document(path: str | Path, max_entries: int = 4096) -> Document:
    p = Path(path)
    suffix = p.suffix.lower()
    if suffix == ".pdf":
        # The PDF path streams and hashes per file rather than reading the whole
        # document into a bytes object, so it does not share this reader's path.
        from .pdf import load_pdf
        return load_pdf(p)
    src = p.read_bytes()
    source_hash = sha256_hex(src)
    source_id = p.name
    # F71: the macro-enabled twins are the same OOXML containers plus a
    # vbaProject.bin part; the "no parser is configured for .docm" refusal
    # pushed macro documents into raw archive dumps downstream.
    if suffix in (".xlsx", ".xlsm", ".xltm", ".xlam",
                  ".docx", ".docm", ".dotm",
                  ".pptx", ".pptm", ".potm", ".ppsm"):
        return _parse_ooxml(p, suffix, source_id, source_hash, src, max_entries)
    if suffix in (".odt", ".ods", ".odp", ".epub"):
        import io
        from ..security import audit_zip_members
        from . import opendoc
        try:
            zf = zipfile.ZipFile(io.BytesIO(src))
        except zipfile.BadZipFile as exc:
            # Claims the format, is not a zip container: typed refusal, same law as
            # OpendocRejected - never an exception at the job boundary.
            return Document(source_id, source_hash, "unsupported", [],
                            DocCoverage(0, 0, method="none",
                                        note=f"not a readable {suffix} package: {exc}"))
        audit_zip_members(zf)
        if len(zf.infolist()) > max_entries:
            raise ExtractionRejected("too many package parts")
        try:
            return opendoc.load_opendoc(zf, suffix, source_id, source_hash)
        except opendoc.OpendocRejected as exc:
            # The package claims the format but carries none of its required parts.
            # An "unsupported" document with a stated reason is the typed refusal:
            # the caller's byte-scan fallback stays labeled as a fallback.
            return Document(source_id, source_hash, "unsupported", [],
                            DocCoverage(0, 0, method="none",
                                        note=f"not a readable {suffix} package: {exc}"))
    if suffix == ".rtf":
        from . import opendoc
        return opendoc.rtf_document(src, source_id, source_hash)
    if suffix in (".doc", ".ppt", ".xls", ".mat"):
        # Real structured readers for the legacy binary formats, replacing the old
        # "scan raw bytes for printable runs" path. A malformed file (truncated OLE
        # header, garbage sector table) is a typed refusal, never a silent flattening.
        from . import legacy
        readers = {".doc": legacy._doc_document, ".ppt": legacy._ppt_document,
                   ".xls": legacy._xls_document, ".mat": legacy._mat_document}
        try:
            return readers[suffix](src, source_id, source_hash)
        except legacy.OleError as exc:
            return Document(source_id, source_hash, "unsupported", [],
                            DocCoverage(0, 0, method="none",
                                        note=f"malformed legacy binary: {exc}"))
    if suffix in (".txt", ".md", ".log", ".csv", ".json"):
        text = src.decode("utf-8", "replace")
        blocks = [Block(t, "page_text", source_id, source_hash, {"line": i + 1})
                  for i, t in enumerate(text.splitlines()) if t.strip()]
        return Document(source_id, source_hash, "text", blocks,
                        DocCoverage(len(blocks), len(blocks), method="native-text"))
    if suffix in (".png", ".jpg", ".jpeg", ".gif", ".bmp", ".tif", ".tiff", ".webp",
                  ".emf", ".wmf", ".svg"):
        # A standalone raster: the pixels ARE the content - no text layer is manufactured.
        # The same region inspection an embedded image gets decides honestly (documents/
        # region_ocr.py): a text-bearing label goes to the engine, a photo or blank render
        # keeps its pixels and pays zero engine calls.
        return Document(source_id, source_hash, "image", [],
                        DocCoverage(1, 0, units_empty=[1], method="raster",
                                    note="standalone raster: no native text layer; the region "
                                         "inspection of the pixels decides whether an engine runs"),
                        meta={"embedded_images": [{"unit": 1, "part": source_id, "ext": suffix}]})
    return Document(source_id, source_hash, "unsupported", [],
                    DocCoverage(0, 0, method="none", note="no parser for this format; not silently flattened"))


def _parse_ooxml(p: Path, suffix: str, source_id: str, source_hash: str, src: bytes, max_entries: int) -> Document:
    import io
    from ..security import audit_zip_members
    try:
        zf = zipfile.ZipFile(io.BytesIO(src))
    except zipfile.BadZipFile as exc:
        return Document(source_id, source_hash, "unsupported", [],
                        DocCoverage(0, 0, method="none",
                                    note=f"not a readable {suffix} package: {exc}"))
    audit_zip_members(zf)
    if len(zf.infolist()) > max_entries:
        raise ExtractionRejected("too many OOXML parts")
    if suffix in (".xlsx", ".xlsm", ".xltm", ".xlam"):
        return _xlsx(zf, source_id, source_hash)
    if suffix in (".docx", ".docm", ".dotm"):
        return _docx(zf, source_id, source_hash)
    return _pptx(zf, source_id, source_hash)


def _shared_strings(zf: zipfile.ZipFile) -> list[str]:
    if "xl/sharedStrings.xml" not in zf.namelist():
        return []
    root = ET.fromstring(zf.read("xl/sharedStrings.xml"))
    out = []
    for si in root.findall(f"{_MAIN_NS}si"):
        # rich text runs concatenate; the parser resolves entities, so astral planes survive
        out.append("".join(t.text or "" for t in si.iter(f"{_MAIN_NS}t")))
    return out


def _xlsx(zf: zipfile.ZipFile, source_id: str, source_hash: str) -> Document:
    strings = _shared_strings(zf)
    wb = ET.fromstring(zf.read("xl/workbook.xml"))
    rels = ET.fromstring(zf.read("xl/_rels/workbook.xml.rels"))
    rid2target = {r.get("Id"): r.get("Target") for r in rels}
    sheets = []
    for sh in wb.iter(f"{_MAIN_NS}sheet"):
        rid = sh.get("{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id")
        target = (rid2target.get(rid) or "").lstrip("/")
        if not target.startswith("xl/"):
            target = "xl/" + target
        sheets.append((sh.get("name"), target))
    blocks: list[Block] = []
    failed: list[int] = []
    corrupt: list[dict[str, str]] = []
    # WHY a sheet produced nothing. "units_failed=[1]" alone leaves the caller guessing
    # whether the part is missing, unresolvable through the relationship table, or corrupt.
    sheet_failures: list[dict[str, str]] = []
    merged_ranges: dict[str, list[str]] = {}
    # A cell that is DECLARED but carries no value is recorded as missing. It is not emitted
    # as a block (an empty cell has no content to cite) and it is never coerced to 0; keeping
    # the reference separately is what makes "explicit 0" and "blank" provably different.
    # Bounded per sheet: a formatted-but-empty 10k-cell grid cannot bloat the payload.
    empty_refs: dict[str, list[str]] = {}
    empty_counts: dict[str, int] = {}
    MAX_EMPTY_REFS = 200
    for si, (name, target) in enumerate(sheets, start=1):
        if not target or target == "xl/":
            sheet_failures.append({"sheet": str(name), "sheet_index": si, "part": "",
                                   "why": "the workbook names a relationship id that the "
                                          "relationship part does not define"})
            failed.append(si)
            continue
        try:
            raw = zf.read(target)
        except KeyError:
            sheet_failures.append({"sheet": str(name), "sheet_index": si, "part": target,
                                   "why": "the sheet part named by the workbook is not in the "
                                          "package"})
            failed.append(si)
            continue
        try:
            root = ET.fromstring(raw)
        except ET.ParseError as exc:
            sheet_failures.append({"sheet": str(name), "sheet_index": si, "part": target,
                                   "why": f"the sheet part is not well-formed XML: {exc}"})
            failed.append(si)
            continue
        # Merged ranges are kept as GEOMETRY, because a cell reference (A1) never matches
        # a range string (A1:B2) by equality. The full declared list is preserved per sheet,
        # including merges whose interior cells are empty.
        merged = [
            (ref, range_bounds(ref))
            for node in root.iter(f"{_MAIN_NS}mergeCell")
            if (ref := node.get("ref")) and _CELL_REF.fullmatch(ref.split(":")[0].strip().upper())
        ]
        merged_ranges[name or f"sheet{si}"] = [m[0] for m in merged]
        merged_index = _merged_index(merged)
        sheet_label = str(name or f"sheet{si}")
        empties: list[str] = []
        empty_total = 0
        for row in root.iter(f"{_MAIN_NS}row"):
            for c in row.findall(f"{_MAIN_NS}c"):
                ref = c.get("r") or ""
                t = c.get("t")
                fnode = c.find(f"{_MAIN_NS}f")
                vnode = c.find(f"{_MAIN_NS}v")
                isnode = c.find(f"{_MAIN_NS}is")
                loc: dict[str, object] = {"sheet": name, "cell": ref, "sheet_index": si}
                area = _merged_for(ref, merged_index) if ref else None
                if area:
                    loc["merged"] = area
                if c.get("s") is not None:
                    loc["style_index"] = c.get("s")
                if t:
                    loc["cell_type"] = t
                if fnode is not None and (fnode.text or "").strip():
                    # Formula TEXT and its CACHED RESULT stay separate fields; a reader that
                    # only sees the concatenation cannot tell a stale cache from a value.
                    cached = vnode.text if vnode is not None else None
                    loc["formula"] = fnode.text
                    loc["cached_value"] = cached
                    if fnode.get("t") == "shared" and fnode.get("si") is not None:
                        loc["shared_formula_id"] = fnode.get("si")
                    text = f"={fnode.text}" + (f" (cached {cached})" if cached else "")
                    kind = "formula"
                elif t == "s" and vnode is not None:
                    raw = (vnode.text or "").strip()
                    if raw.isdigit() and 0 <= int(raw) < len(strings):
                        text = strings[int(raw)]
                    else:
                        # A shared-string index out of range is corruption, not an empty cell.
                        corrupt.append({"sheet": str(name), "cell": ref, "why":
                                        f"shared-string index {raw!r} is outside the "
                                        f"{len(strings)} entry table"})
                        continue
                    kind = "cell"
                elif t == "e":
                    text = (vnode.text or "").strip() if vnode is not None else ""
                    corrupt.append({"sheet": str(name), "cell": ref,
                                    "why": f"cell holds an error value: {text or 'unspecified'}"})
                    continue
                elif isnode is not None:
                    text = "".join(x.text or "" for x in isnode.iter(f"{_MAIN_NS}t"))
                    kind = "cell"
                else:
                    text = vnode.text if vnode is not None else ""
                    kind = "cell"
                    if vnode is None and fnode is None:
                        # A genuinely missing value is recorded as missing, never coerced to 0.
                        loc["value_missing"] = True
                        if ref:
                            empty_total += 1
                            if len(empties) < MAX_EMPTY_REFS:
                                empties.append(ref)
                if not text.strip():
                    continue
                blocks.append(Block(text, kind, source_id, source_hash, loc))
        if empty_total:
            empty_refs[sheet_label] = empties
            empty_counts[sheet_label] = empty_total
    total = len(sheets)
    cov = DocCoverage(total, total - len(failed), units_failed=failed, method="ooxml-cellwise",
                      note="formulas kept with cached values; number formats are not re-derived here")
    cov.units_succeeded = [si for si in range(1, total + 1) if si not in set(failed)]
    return Document(source_id, source_hash, "xlsx", blocks, cov,
                    {"sheets": [s[0] for s in sheets],
                     "merged_ranges": merged_ranges,
                     "corrupt_cells": corrupt,
                     "empty_cells": {label: {"count": empty_counts[label],
                                             "refs": empty_refs[label],
                                             **({"truncated": len(empty_refs[label]) < empty_counts[label]}
                                                if len(empty_refs[label]) < empty_counts[label] else {})}
                                     for label in empty_refs},
                     "sheet_failures": sheet_failures,
                     "embedded_images": _xlsx_image_inventory(zf, sheets),
                     "unit_numbering": "1-based sheet index"})


_M_NS = "{http://schemas.openxmlformats.org/officeDocument/2006/math}"
_PKG_R_NS = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}"
_C_NS = "{http://schemas.openxmlformats.org/drawingml/2006/chart}"

# A footnote of type separator/continuationSeparator IS the mark (a dash), not content.
_DOCX_SEP_TYPES = frozenset({"separator", "continuationSeparator"})


def _omml_text(el) -> str:
    """Linearize one OMML math node. Fractions read (num)/(den); everything else
    concatenates m:t. This keeps equations addressable — "(u+7)/(v-4)" survives as
    text — without pretending the reader typesets math.
    """
    if el.tag == f"{_M_NS}f":
        num = el.find(f"{_M_NS}num")
        den = el.find(f"{_M_NS}den")
        return f"({_omml_text(num) if num is not None else ''})/({_omml_text(den) if den is not None else ''})"
    children = list(el)
    if children:
        return "".join(_omml_text(c) for c in children)
    return el.text if el.tag == f"{_M_NS}t" else ""


def _docx_text_of(el) -> str:
    """Text of a w:p / w:tc / w:footnote in document order, with the revision view
    preserved and OMML linearized.

    w:delText — the text of a tracked deletion — is INVISIBLE to an iter(w:t) scan,
    so the old reader silently dropped the struck-through figure and presented a
    document whose visible text was "910 seats307 seats" as if the deletion had
    never happened. Deletions stay inline, labeled; insertions are ordinary w:t.
    """
    parts: list[str] = []

    def walk(node) -> None:
        if node.tag == f"{_M_NS}oMath":
            linear = _omml_text(node)
            if linear.strip():
                parts.append(f" {linear} ")
            return
        if node.tag == f"{_W_NS}t":
            parts.append(node.text or "")
            return
        if node.tag == f"{_W_NS}delText":
            t = (node.text or "").strip()
            if t:
                parts.append(f" [deleted revision: {t}] ")
            return
        for child in node:
            walk(child)

    walk(el)
    return "".join(parts)


def _docx_side_parts(zf: zipfile.ZipFile) -> list[tuple[str, str, dict[str, object]]]:
    """Footnotes, endnotes, headers and footers — parts a body scan never sees.

    The old reader declared them "not_extracted" and a model quoting the document
    could not see the footnote deadline or the distribution group in the header.
    Returns (text, part-label, loc) tuples; the caller attaches source identity.
    """
    blocks: list[tuple[str, str, dict[str, object]]] = []
    for part, label, tag in (("word/footnotes.xml", "footnote", f"{_W_NS}footnote"),
                             ("word/endnotes.xml", "endnote", f"{_W_NS}endnote")):
        if part not in zf.namelist():
            continue
        try:
            root = ET.fromstring(zf.read(part))
        except ET.ParseError:
            continue
        for note in root.findall(tag):
            if note.get(f"{_W_NS}type") in _DOCX_SEP_TYPES:
                continue
            text = _docx_text_of(note).strip()
            if text:
                blocks.append((text, label, {"part": label, "id": note.get(f"{_W_NS}id")}))
    rels_part = "word/_rels/document.xml.rels"
    if rels_part in zf.namelist():
        try:
            rels = ET.fromstring(zf.read(rels_part))
        except ET.ParseError:
            rels = None
        if rels is not None:
            wanted = []
            for r in rels:
                rtype = str(r.get("Type") or "")
                if rtype.endswith("/header") or rtype.endswith("/footer"):
                    label = "header" if rtype.endswith("/header") else "footer"
                    target = str(r.get("Target") or "").lstrip("/")
                    if target and not target.startswith("word/"):
                        target = "word/" + target
                    if target in zf.namelist():
                        wanted.append((label, target))
            for label, target in sorted(wanted, key=lambda w: (w[0], w[1])):
                try:
                    root = ET.fromstring(zf.read(target))
                except (KeyError, ET.ParseError):
                    continue
                body = root.find(f"{_W_NS}hdr") if label == "header" else root.find(f"{_W_NS}ftr")
                text = _docx_text_of(body if body is not None else root).strip()
                if text:
                    name = target.rsplit("/", 1)[-1].rsplit(".", 1)[0]
                    blocks.append((text, label, {"part": label, "name": name}))
    return blocks


def _docx(zf: zipfile.ZipFile, source_id: str, source_hash: str) -> Document:
    root = ET.fromstring(zf.read("word/document.xml"))
    blocks: list[Block] = []
    body = root.find(f"{_W_NS}body")
    section = 0
    table_no = 0
    if body is None:
        return Document(source_id, source_hash, "docx", [],
                        DocCoverage(0, 0, method="ooxml", note="document body is empty"))
    for el in body:
        if el.tag == f"{_W_NS}p":
            text = _docx_text_of(el)
            style = el.find(f"{_W_NS}pPr/{_W_NS}pStyle")
            name = (style.get(f"{_W_NS}val") or "") if style is not None else ""
            if not text.strip():
                continue
            kind = "heading" if name.lower().startswith("heading") or name.lower() == "title" else "paragraph"
            # Citation convention: every unit id this reader emits is 1-based (pages, sheets,
            # slides AND paragraphs). A 0-based paragraph id next to a 1-based page id is the
            # kind of off-by-one that makes a citation name the wrong block, and the document
            # meta below already declares "1-based block/paragraph index".
            loc: dict[str, object] = {"paragraph": len(blocks) + 1}
            if kind == "heading":
                section += 1
                loc["section"] = name or "heading"
            blocks.append(Block(text, kind, source_id, source_hash, loc))
        elif el.tag == f"{_W_NS}tbl":
            table_no += 1

            for row_no, tr in enumerate(el.findall(f"{_W_NS}tr"), start=1):
                cells = [_docx_text_of(tc) for tc in tr.findall(f"{_W_NS}tc")]

                blocks.append(Block(
                    " | ".join(cells),
                    "table_row",
                    source_id,
                    source_hash,
                    {"table": table_no, "row": row_no, "cells": cells},
                ))
            # Table identity is the ordinal of the table in the body, not the running block
            # count: interleaved paragraphs used to shift every later row's table number.
            # Nested tables, vertically merged cells (vMerge) and heading-in-cell content
            # are NOT reconstructed by this reader and stay declared limitations below.
    side = _docx_side_parts(zf)
    for text, _label, loc in side:
        blocks.append(Block(text, "note", source_id, source_hash, loc))
    deleted = sum(1 for b in blocks if "[deleted revision:" in b.text)
    cov = DocCoverage(1, 1, method="ooxml",
                      note="heading hierarchy and table cells preserved; tracked deletions kept "
                           "inline labeled '[deleted revision: ...]'; footnotes/endnotes/headers/footers read")
    cov.units_succeeded = [1]
    return Document(source_id, source_hash, "docx", blocks, cov,
                    {"unit_numbering": "1-based block/paragraph index; tables are numbered "
                                       "by body order",
                     "tables": table_no,
                     "embedded_images": _docx_image_inventory(zf),
                     "revision_paragraphs": deleted,
                     "side_parts": sorted({str(loc.get("part")) for _t, _l, loc in side}),
                     "not_extracted": ["nested tables", "vertically merged cells",
                                       "text boxes and drawing shapes",
                                       "numbered-list restart state",
                                       "equation typesetting (OMML is linearized, not rendered)"]})


def _slide_targets(zf: zipfile.ZipFile, slide_part: str) -> dict[str, str]:
    """Relationship type-suffix -> resolved package path, for one slide part."""
    import posixpath
    rel_part = f"ppt/slides/_rels/{slide_part.rsplit('/', 1)[-1]}.rels"
    out: dict[str, str] = {}
    if rel_part not in zf.namelist():
        return out
    try:
        rels = ET.fromstring(zf.read(rel_part))
    except ET.ParseError:
        return out
    for r in rels:
        rtype = str(r.get("Type") or "")
        target = str(r.get("Target") or "")
        if not rtype or not target or target.startswith(("http:", "https:")):
            continue
        # A leading "/" makes the target package-absolute; joining it onto the
        # part's folder would invent "ppt/slides/ppt/charts/chart1.xml".
        if target.startswith("/"):
            resolved = posixpath.normpath(target.lstrip("/"))
        else:
            resolved = posixpath.normpath(posixpath.join("ppt/slides", target))
        out[rtype.rsplit("/", 1)[-1]] = resolved
    return out


def _pptx_display_order(zf: zipfile.ZipFile, names: list[str]) -> tuple[list[str], str]:
    """Slide parts in PRESENTATION order.

    sldIdLst (via the presentation rels) is the display order; slideN.xml filenames
    are package-creation order and disagree in real decks (a deck whose sldIdLst is
    rId4,rId2,rId3 shows slide3.xml first). Numbering notes, charts and citations by
    filename put every fact on the wrong slide.
    """
    byname = {n.rsplit("/", 1)[-1]: n for n in names}
    try:
        pres = ET.fromstring(zf.read("ppt/presentation.xml"))
        rels = ET.fromstring(zf.read("ppt/_rels/presentation.xml.rels"))
    except (KeyError, ET.ParseError):
        return list(names), "slideN.xml order (no readable presentation.xml)"
    rid2target = {r.get("Id"): str(r.get("Target") or "") for r in rels}
    lst = pres.find(f"{_P_NS}sldIdLst")
    if lst is None:
        return list(names), "slideN.xml order (presentation.xml has no sldIdLst)"
    order: list[str] = []
    unresolved = 0
    for sld in lst.findall(f"{_P_NS}sldId"):
        target = rid2target.get(sld.get(f"{_PKG_R_NS}id"), "").lstrip("/")
        if target and not target.startswith("ppt/"):
            target = "ppt/" + target
        part = byname.get(target.rsplit("/", 1)[-1])
        if part and part not in order:
            order.append(part)
        else:
            unresolved += 1
    if unresolved:
        # An sldId whose r:id has no relationship (or targets a non-slide part) makes the
        # whole list untrustworthy as an ordering: applying the resolvable prefix silently
        # MOVES the unresolvable slide's number (a title slide lands on slide 3). Fall back
        # to the full filename order and say why.
        return list(names), ("slideN.xml order (p:sldIdLst has unresolvable slide "
                             f"references: {unresolved})")
    order.extend(n for n in names if n not in order)  # parts outside sldIdLst stay visible
    return order, "p:sldIdLst display order"


def _chart_lines(chart_name: str, root) -> list[str]:
    """Data-cached chart series as self-labeled text lines.

    A chart's strCache/multiLvlStrCache (categories) and numCache (values) are the
    numbers the deck SHOWS; a reader that skips charts loses "East=83 West=42"
    entirely. Only CACHED values are emitted - nothing is recomputed.
    """
    lines: list[str] = []
    for ser in root.iter(f"{_C_NS}ser"):
        tx = ser.find(f"{_C_NS}tx")
        name = "".join(v.text or "" for v in tx.iter(f"{_C_NS}v")).strip() if tx is not None else ""
        def cached_values(where) -> list[str]:
            if where is None:
                return []
            out = []
            for pt in where.iter(f"{_C_NS}pt"):
                # multiLvlStrCache nests one <c:v> per level; the leaf is the label.
                vs = [(v.text or "").strip() for v in pt.iter(f"{_C_NS}v")]
                out.append(next((v for v in reversed(vs) if v), ""))
            return out
        cats = cached_values(ser.find(f"{_C_NS}cat"))
        vals = cached_values(ser.find(f"{_C_NS}val"))
        if cats and vals:
            pairs = ", ".join(f"{c}={v}" for c, v in zip(cats, vals))
            shape = ""
        else:
            # F64: scatter/bubble series cache PAIRED points under
            # c:xVal/c:yVal — a cat/val-only reader skipped every scatter
            # series and the deck lost its data (deck-4.pptx: the model saw
            # only the slide words "My/Scatter/Chart", never "Sales" / 8.2).
            xs = cached_values(ser.find(f"{_C_NS}xVal"))
            ys = cached_values(ser.find(f"{_C_NS}yVal"))
            pairs = ", ".join(f"({x}, {y})" for x, y in zip(xs, ys))
            shape = " scatter points"
        if not pairs:
            continue
        label = f' [chart {chart_name} series "{name}"{shape}]' if name else f" [chart {chart_name}{shape}]"
        lines.append(f"{label} {pairs}")
    return lines




def _docx_image_inventory(zf: zipfile.ZipFile) -> list[dict]:
    """Rasters anchored in the document body: {unit, part, ext}.

    unit is the 1-based body paragraph ELEMENT ordinal (empty paragraphs counted), so an
    image in a text-free paragraph still has a provable anchor. The OCR decision needs
    the image's existence and position; its bytes stay in the package.
    """
    rel_part = "word/_rels/document.xml.rels"
    rid2target: dict[str, str] = {}
    if rel_part in zf.namelist():
        try:
            for r in ET.fromstring(zf.read(rel_part)):
                t = str(r.get("Target") or "")
                if t and not t.startswith("http"):
                    rid2target[str(r.get("Id"))] = "word/" + t.lstrip("/") \
                        if not t.startswith("/") else t.lstrip("/")
        except ET.ParseError:
            pass
    if "word/document.xml" not in zf.namelist() or not rid2target:
        return []
    try:
        root = ET.fromstring(zf.read("word/document.xml"))
    except ET.ParseError:
        return []
    body = root.find(f"{_W_NS}body")
    out: list[dict] = []
    if body is None:
        return out
    para = 0
    for el in body.iter(f"{_W_NS}p"):
        para += 1
        for blip in el.iter(f"{_A_NS}blip"):
            rid = blip.get(f"{_PKG_R_NS}embed")
            part = rid2target.get(rid or "")
            if part:
                out.append({"unit": para, "part": part,
                            "ext": part.rsplit(".", 1)[-1].lower()})
    return out


def _xlsx_image_inventory(zf: zipfile.ZipFile, sheets: list[tuple]) -> list[dict]:
    """Rasters anchored on each sheet: {unit, part, ext, anchor}."""
    import posixpath
    out: list[dict] = []
    for si, (_name, target) in enumerate(sheets, start=1):
        rel_part = f"xl/worksheets/_rels/{target.rsplit('/', 1)[-1]}.rels"
        if rel_part not in zf.namelist():
            continue
        try:
            rels = ET.fromstring(zf.read(rel_part))
        except ET.ParseError:
            continue
        for r in rels:
            if not str(r.get("Type") or "").endswith("/drawing"):
                continue
            dtarget = str(r.get("Target") or "")
            dpart = dtarget.lstrip("/") if dtarget.startswith("/") \
                else posixpath.normpath(posixpath.join("xl/worksheets", dtarget))
            drel_part = f"xl/drawings/_rels/{dpart.rsplit('/', 1)[-1]}.rels"
            if dpart not in zf.namelist() or drel_part not in zf.namelist():
                continue
            # Two-pass anchors are the cell the picture sits ON; without a from-cell the
            # region is still locatable to the sheet itself.
            anchors: dict[str, str] = {}
            try:
                droot = ET.fromstring(zf.read(dpart))
                _X = "{http://schemas.openxmlformats.org/drawingml/2006/spreadsheetDrawing}"
                for anchor in droot.iter(f"{_X}twoCellAnchor"):
                    frm = anchor.find(f"{_X}from")
                    cell = ""
                    if frm is not None:
                        col = frm.find(f"{_X}col")
                        row = frm.find(f"{_X}row")
                        if col is not None and row is not None:
                            ci = int(col.text or 0)
                            cell = f"{_col_letter(ci + 1)}{int(row.text or 0) + 1}"
                    for rid in anchor.iter(f"{{http://schemas.openxmlformats.org/drawingml/2006/main}}blip"):
                        anchors[rid.get(f"{_PKG_R_NS}embed") or ""] = cell
            except (ET.ParseError, ValueError):
                pass
            try:
                drels = ET.fromstring(zf.read(drel_part))
            except ET.ParseError:
                continue
            for r in drels:
                t = str(r.get("Target") or "")
                if not t or t.startswith("http"):
                    continue
                part = t.lstrip("/") if t.startswith("/") \
                    else posixpath.normpath(posixpath.join("xl/drawings", t))
                out.append({"unit": si, "part": part,
                            "ext": part.rsplit(".", 1)[-1].lower(),
                            "anchor": anchors.get(str(r.get("Id")), "")})
    return out


def _col_letter(idx: int) -> str:
    s = ""
    while idx > 0:
        idx, rem = divmod(idx - 1, 26)
        s = chr(65 + rem) + s
    return s


def _pptx(zf: zipfile.ZipFile, source_id: str, source_hash: str) -> Document:
    names = [n for n in zf.namelist()
             if n.startswith("ppt/slides/slide") and n.endswith(".xml") and "/_rels/" not in n]
    names.sort(key=lambda n: int("".join(ch for ch in n if ch.isdigit()) or 0))
    names, order_note = _pptx_display_order(zf, names)
    notes = {n for n in zf.namelist() if n.startswith("ppt/notesSlides/notesSlide")}
    blocks: list[Block] = []
    failed: list[int] = []
    charts_seen: list[str] = []
    images_seen: list[dict] = []
    for i, n in enumerate(names, start=1):
        try:
            root = ET.fromstring(zf.read(n))
        except (KeyError, ET.ParseError):
            failed.append(i)
            continue
        for shape in root.iter(f"{_P_NS}sp"):
            text = "\n".join(t.text or "" for t in shape.iter(f"{_A_NS}t"))
            if text.strip():
                blocks.append(Block(text.strip(), "paragraph", source_id, source_hash, {"slide": i}))
        targets = _slide_targets(zf, n)
        # Every raster the slide carries (a type-keyed rels map collapses multiple
        # images to one): the region inventory the OCR decision inspects.
        import posixpath
        srel = f"ppt/slides/_rels/{n.rsplit('/', 1)[-1]}.rels"
        if srel in zf.namelist():
            try:
                for r in ET.fromstring(zf.read(srel)):
                    if str(r.get("Type") or "").endswith("/image"):
                        t = str(r.get("Target") or "")
                        if not t or t.startswith("http"):
                            continue
                        part = t.lstrip("/") if t.startswith("/") \
                            else posixpath.normpath(posixpath.join("ppt/slides", t))
                        images_seen.append({"unit": i, "part": part,
                                            "ext": part.rsplit(".", 1)[-1].lower()})
            except ET.ParseError:
                pass
        note_file = targets.get("notesSlide")
        if note_file is None:
            # Generators that omit the slide rels (minimal packages) keep the
            # filename convention: slideN.xml <-> notesSlideN.xml. Keyed by the
            # FILE number, not the display ordinal, because the pairing lives
            # in the filenames.
            fn = int("".join(ch for ch in n.rsplit("/", 1)[-1] if ch.isdigit()) or 0)
            note_file = f"ppt/notesSlides/notesSlide{fn}.xml"
        if note_file in notes:
            try:
                nroot = ET.fromstring(zf.read(note_file))
                # A notesSlide part is not only the author's notes: it also carries
                # the slide-number / footer / header / date placeholders that every
                # generator emits. Joining EVERY <a:t> therefore produced "1", "2",
                # "3" as note text for a deck with no notes at all, and pollutes a
                # deck that does have them. Only the non-managed placeholders are
                # the author's words (D-071).
                parts = []
                for shape in nroot.iter(f"{_P_NS}sp"):
                    ph = shape.find(f"{_P_NS}nvSpPr/{_P_NS}nvPr/{_P_NS}ph")
                    if ph is not None and ph.get("type") in _NOTES_PLACEHOLDER_TYPES:
                        continue
                    text = "\n".join(t.text or "" for t in shape.iter(f"{_A_NS}t"))
                    if text.strip():
                        parts.append(text.strip())
                ntext = "\n".join(parts).strip()
                if ntext:
                    blocks.append(Block(ntext, "note", source_id, source_hash, {"slide": i, "part": "notes"}))
            except (KeyError, ET.ParseError):
                failed.append(i)
        chart_part = targets.get("chart")
        if chart_part and chart_part in zf.namelist():
            try:
                croot = ET.fromstring(zf.read(chart_part))
            except (KeyError, ET.ParseError):
                continue
            chart_name = chart_part.rsplit("/", 1)[-1]
            charts_seen.append(chart_name)
            for line in _chart_lines(chart_name, croot):
                # BLOCK_KINDS is a closed contract; a chart series is self-labeled
                # paragraph text carrying its chart part in loc, not a new kind.
                blocks.append(Block(line, "paragraph", source_id, source_hash,
                                    {"slide": i, "chart": chart_name}))
    cov = DocCoverage(len(names), len(names) - len(failed), units_failed=failed, method="ooxml",
                      note=f"slide text, speaker notes (via slide rels) and chart data caches kept "
                           f"separate; slide numbering is {order_note}; animations are not described")
    cov.units_succeeded = [i for i in range(1, len(names) + 1) if i not in set(failed)]
    return Document(source_id, source_hash, "pptx", blocks, cov,
                    {"unit_numbering": f"1-based slide ordinal ({order_note})",
                     "slides": len(names),
                     "note_parts": sorted(notes),
                     "charts": sorted(set(charts_seen)),
                     "embedded_images": images_seen,
                     "not_extracted": ["SmartArt", "animations", "slide master text",
                                       "hyperlink relationship targets",
                                       "chart styling and axis scaling (cached values only)"]})
