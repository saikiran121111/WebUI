"""Synthetic temporal-correctness probe: do the clocks and cut times land where we said?

SCOPE, stated up front so this is never mistaken for a quality result:
the clip is generated by ffmpeg from declared lavfi sources, so the ground truth
is the DECLARED cut schedule, not a human judgement about semantics. This probe
measures one thing - that a decode, its timestamps and the scan's parse agree with
that schedule. It says nothing about whether the system can UNDERSTAND an event in
a real recording, and it does not satisfy the frozen `temporal_video_localisation`
family, which stays not_run until a human-labelled real video is evaluated.

Why a synthetic clip is still worth running: the clock laws (presentation time,
stream offset, passthrough frame timing, the best_eff_pts_time double-count trap) are
the kind of defect that only shows up against a real decoder, and a real decoder is
exactly what we can drive deterministically here.
"""
from __future__ import annotations

import json
import os
import subprocess
import time
from typing import Any

from .. import processes
from ..models.binaries import path_for
from ..video import scenes
from .metrics import temporal_localization

# Declared schedule. Segment i occupies [i*SEG_S, (i+1)*SEG_S), so a hard visual
# change exists at exactly SEG_S, 2*SEG_S, 3*SEG_S.
SEG_S = 3.0
# Each entry is a lavfi SOURCE (options are appended by build_synthetic_clip). Sources are
# chosen for a large difference BETWEEN segments and none WITHIN a segment, so a detected
# cut is a real property of the clip rather than an artifact of a moving pattern. The
# measured scene values for this exact clip are asserted in tests/test_video_probe.py.
SEGMENTS: tuple[tuple[str, float], ...] = (("smptebars", SEG_S), ("rgbtestsrc", SEG_S),
                                           ("smptehdbars", SEG_S), ("yuvtestsrc", SEG_S))
TRUTH_CUTS: tuple[float, ...] = tuple(round(i * SEG_S, 3)
                                      for i in range(1, len(SEGMENTS)))
SEG_TOLERANCE_S = 0.6
PROBE_TIMEOUT_S = 180.0

SCOPE_NOTE = ("synthetic ffmpeg-generated clip with a DECLARED cut schedule: measures decode "
              "clocks, timestamp parsing and cut detection only. It is not evidence about "
              "semantic event understanding, and it does not replace the frozen "
              "temporal_video_localisation gate, which needs a human-labelled real video.")


def _ffmpeg(ffmpeg: str | None = None) -> str:
    return ffmpeg or path_for("ffmpeg") or ""


def _run(cmd: list[str], timeout_s: float) -> subprocess.CompletedProcess:
    return processes.run_captured(cmd, timeout=timeout_s, text=True)


def build_synthetic_clip(dest_dir: str, ffmpeg: str | None = None) -> dict[str, Any]:
    """Generate the clip and return its facts, including the schedule we declared."""
    exe = _ffmpeg(ffmpeg)
    if not exe:
        return {"ok": False, "error": "ffmpeg_not_installed",
                "detail": "no validated ffmpeg copy (override, PATH or project-local)"}
    os.makedirs(dest_dir, exist_ok=True)
    parts: list[str] = []
    for index, (source, seconds) in enumerate(SEGMENTS):
        part = os.path.join(dest_dir, "ruke-probe-seg-%d.mp4" % index)
        proc = _run([exe, "-y", "-hide_banner", "-loglevel", "error", "-f", "lavfi",
                     "-i", "%s=s=160x120:r=10:d=%g" % (source, seconds), "-t", "%g" % seconds,
                     "-pix_fmt", "yuv420p", part], PROBE_TIMEOUT_S)
        if proc.returncode != 0 or not os.path.exists(part):
            return {"ok": False, "error": "clip_generation_failed", "segment": index,
                    "detail": (proc.stderr or "")[-400:]}
        parts.append(part)
    listing = os.path.join(dest_dir, "ruke-probe-concat.txt")
    with open(listing, "w", encoding="utf-8") as fh:
        fh.write("\n".join("file '%s'" % p.replace("\\", "/") for p in parts))
    clip = os.path.join(dest_dir, "ruke-probe-cuts.mp4")
    proc = _run([exe, "-y", "-hide_banner", "-loglevel", "error", "-f", "concat", "-safe", "0",
                 "-i", listing, "-c", "copy", clip], PROBE_TIMEOUT_S)
    if proc.returncode != 0 or not os.path.exists(clip):
        return {"ok": False, "error": "clip_concat_failed", "detail": (proc.stderr or "")[-400:]}
    duration = SEG_S * len(SEGMENTS)
    return {"ok": True, "clip": clip, "bytes": os.path.getsize(clip), "duration": duration,
            "segments": [{"source": s, "seconds": d} for s, d in SEGMENTS],
            "declared_cut_times": list(TRUTH_CUTS), "ffmpeg": os.path.basename(exe)}


def probe(dest_dir: str, threshold: float = 0.3, budget: int = 12,
          ffmpeg: str | None = None) -> dict[str, Any]:
    """Run the whole decode->scan->window->localise chain against the declared schedule."""
    started = time.monotonic()
    clip = build_synthetic_clip(dest_dir, ffmpeg=ffmpeg)
    if not clip["ok"]:
        return {"ok": False, "clip": clip, "scope_note": SCOPE_NOTE,
                "elapsed_ms": int((time.monotonic() - started) * 1000)}
    scan = scenes.scan_scene_cuts(clip["clip"], duration=clip["duration"], threshold=threshold)
    plan = scenes.sample_windows(clip["duration"], cuts=scan.cuts, budget=budget)
    pred = [(w.start, w.end) for w in plan.windows]
    # Two DIFFERENT questions, scored separately so neither is flattered by the other:
    #  (1) did the detected CUT TIMES land on the declared schedule (point accuracy), and
    #  (2) does at least one sampled window actually OVERLAP each declared event, i.e. is
    #      the event inside the evidence the model would be shown. A wide coverage window
    #      centred far away passes (2) and must never be reported as clock accuracy.
    truths = [(c - SEG_S / 20.0, c + SEG_S / 20.0) for c in TRUTH_CUTS]
    local = temporal_localization([(c, c) for c in scan.cuts], truths, SEG_TOLERANCE_S)
    covered = [any(w.start < hi and w.end > lo for w in plan.windows) for lo, hi in truths]
    window_cover = {"n_truth": len(truths),
                    "covered": sum(1 for x in covered if x),
                    "hit_rate": (sum(1 for x in covered if x) / float(len(truths))) if truths else None,
                    "uncovered_declared_events": [TRUTH_CUTS[i] for i, x in enumerate(covered)
                                                  if not x]}
    # The honesty invariant: a bounded sample must never claim completeness.
    # Read the machine flag, not a sentence: a probe that greps for the word
    # "unexamined" only proves the note still contains that word, which is why the
    # wording used to be load-bearing. Plan seconds are PLANNED, never inspected, and
    # the decode prefix is a separate measured number.
    honesty = {"note": plan.honest_note,
               "claims_completeness": plan.claims_inspected_coverage,
               "planned_seconds": round(plan.planned_seconds, 3),
               "planned_windows": len(plan.windows),
               "planning_is_never_inspection": True,
               "total_seconds": clip["duration"],
               "coverage_is_partial": (plan.planned_seconds < clip["duration"] - 1e-6),
               "measured_decode_prefix_s": scan.scanned_seconds,
               "prefix_measured": scan.prefix_measured}
    cut_err: list[float] = []
    for truth in TRUTH_CUTS:
        if scan.cuts:
            cut_err.append(min(abs(c - truth) for c in scan.cuts))
    detect = {"n_truth": len(TRUTH_CUTS),
              "found_within_tolerance": sum(1 for e in cut_err if e <= SEG_TOLERANCE_S),
              "mean_abs_error_s": (sum(cut_err) / len(cut_err)) if cut_err else None,
              "spurious_cuts": max(0, len(scan.cuts) - len(TRUTH_CUTS))}
    ok = bool(scan.ok and not scan.truncated
              and local["hit_rate"] == 1.0
              and local["mean_abs_error_s"] is not None
              and local["mean_abs_error_s"] <= SEG_TOLERANCE_S
              and window_cover["hit_rate"] == 1.0
              and not honesty["claims_completeness"])
    return {"ok": ok, "clip": clip, "scope_note": SCOPE_NOTE,
            "scan": {"cuts": scan.cuts, "ok": scan.ok, "error": scan.error, "detail": scan.detail,
                     "truncated": scan.truncated, "scanned_seconds": scan.scanned_seconds,
                     "prefix_measured": scan.prefix_measured,
                     "progress_updates": scan.progress_updates,
                     "log_chars": scan.log_chars, "log_capped": scan.log_capped,
                     "threshold": scan.threshold, "elapsed_ms": scan.elapsed_ms,
                     "detected_within_tolerance": detect["found_within_tolerance"],
                     "detection_mean_abs_error_s": detect["mean_abs_error_s"],
                     "spurious_cut_count": detect["spurious_cuts"]},
            "windows": [{"start": w.start, "end": w.end, "kind": w.kind, "reason": w.reason}
                        for w in plan.windows],
            "localisation": local, "window_coverage": window_cover, "honesty": honesty,
            "tolerance_s": SEG_TOLERANCE_S,
            "elapsed_ms": int((time.monotonic() - started) * 1000)}


def main(argv: list[str] | None = None) -> int:
    import argparse
    ap = argparse.ArgumentParser(description="synthetic temporal-correctness probe")
    ap.add_argument("--dir", default=None, help="where to write the generated clip")
    ap.add_argument("--out", default=None, help="write the full JSON report here")
    ap.add_argument("--threshold", type=float, default=0.3)
    args = ap.parse_args(list(argv) if argv is not None else None)
    dest = args.dir or os.path.join(os.environ.get("TEMP", "."), "ruke-temporal-probe")
    report = probe(dest, threshold=args.threshold)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            json.dump(report, fh, ensure_ascii=False, indent=2, sort_keys=True)
    if not report["ok"] and "clip" in report and not report["clip"].get("ok"):
        print("probe blocked: %s %s" % (report["clip"].get("error"),
                                        report["clip"].get("detail", "")[:200]))
        return 3
    print("clip %s (%s bytes, %.1fs) ffmpeg=%s"
          % (report["clip"]["clip"], report["clip"]["bytes"], report["clip"]["duration"],
             report["clip"]["ffmpeg"]))
    print("declared cuts: %s" % (report["clip"]["declared_cut_times"],))
    print("detected cuts: %s truncated=%s error=%s"
          % (report["scan"]["cuts"], report["scan"]["truncated"], report["scan"]["error"]))
    print("detection: %d/%d within %.2fs, mean_abs_err=%s, spurious=%d"
          % (report["scan"]["detected_within_tolerance"], report["localisation"]["n_truth"],
             report["tolerance_s"], report["scan"]["detection_mean_abs_error_s"],
             report["scan"]["spurious_cut_count"]))
    loc = report["localisation"]
    print("cut-time localisation: hit_rate=%s mean_abs_error_s=%s over n=%d (windows=%d)"
          % (loc["hit_rate"], loc["mean_abs_error_s"], loc["n_truth"], len(report["windows"])))
    wc = report["window_coverage"]
    print("declared events inside a sampled window: %s/%s uncovered=%s"
          % (wc["covered"], wc["n_truth"], wc["uncovered_declared_events"]))
    print("honesty: %s" % report["honesty"]["note"])
    print("decode prefix: %.1fs of %.1fs (prefix_measured=%s, progress_updates=%s)"
          % (report["scan"]["scanned_seconds"], report["clip"]["duration"],
             report["scan"]["prefix_measured"], report["scan"]["progress_updates"]))
    print("SCOPE: %s" % report["scope_note"])
    return 0 if report["ok"] else 1


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
